#Generates held-note metadata for the imported instrument recordings

import argparse
from functools import cache
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
SOUNDS = ROOT / "sound/musical_instruments"
OUTPUT = ROOT / "code/modules/items/instruments/instrument_sustain_samples.dm"
NOTES = ("c", "c-", "d", "d-", "e", "f", "f-", "g", "g-", "a", "a-", "b")
# Family: playable range, maximum pitch shift, filename octave offset.
IMPORTED = {
    "guitar": ("d2", "c6", 0, 0),
    "saxophone": ("g3", "c6", 3, 1),
}
VELOCITIES = ((2, 0, 65), (3, 66, 99), (4, 100, 127))
PIANO_NAME = re.compile(r"jhpiano_(nosus|sus|nosusrel)_close_([a-g]s?\d+)_vl([234])_rr1")


def note_number(name):
    name = name.replace("s", "-")
    return (int(name[-1]) + 1) * 12 + NOTES.index(name[:-1])


def note_name(number):
    return NOTES[number % 12] + str(number // 12 - 1)


@cache
def duration(path):
    rate = serial = None
    last_granule = 0
    with path.open("rb") as audio:
        while header := audio.read(27):
            if len(header) != 27 or header[:5] != b"OggS\x00":
                raise ValueError(f"Invalid OGG page: {path}")
            granule, page_serial = struct.unpack_from("<QI", header, 6)
            segments = audio.read(header[26])
            if len(segments) != header[26]:
                raise ValueError(f"Truncated OGG page: {path}")
            packet = audio.read(sum(segments))
            if len(packet) != sum(segments):
                raise ValueError(f"Truncated OGG packet: {path}")
            if rate is None:
                if len(packet) < 16 or packet[:7] != b"\x01vorbis":
                    raise ValueError(f"Expected Vorbis audio: {path}")
                rate = struct.unpack_from("<I", packet, 12)[0]
                serial = page_serial
            if page_serial != serial:
                raise ValueError(f"Multiple OGG streams: {path}")
            if granule != 0xFFFFFFFFFFFFFFFF:
                last_granule = granule
    if not rate or not last_granule:
        raise ValueError(f"Missing audio duration: {path}")
    milliseconds = (last_granule * 1000 + rate - 1) // rate
    return f"{milliseconds / 1000:.3f}".rstrip("0").rstrip(".")


def resource(path):
    return "'" + path.relative_to(ROOT).as_posix() + "'"


def family_rows(family, first, last, shift, octave, layer=""):
    recordings = []
    # Filename order preserves the existing nearest-note ties.
    for path in sorted((SOUNDS / family / "sustain" / layer).glob("*.ogg")):
        root = note_number(path.stem.rsplit("_", 1)[1]) + octave * 12
        recordings.append((path, root))
    if not recordings:
        raise ValueError(f"No imported recordings for {family}")
    for number in range(note_number(first), note_number(last) + 1):
        note = note_name(number)
        path, root = min(recordings, key=lambda item: abs(item[1] - number))
        if abs(root - number) > shift:
            continue
        yield f'\t\t"{note}" = list({resource(path)}, {duration(path)}, {number - root}),'


def sample_section(family, rows, options=""):
    yield f'\tadd_instrument_sample_section(., "{family}", list('
    yield from rows
    yield f"\t){', ' + options if options else ''})"
    yield ""


def piano_sections():
    groups = {}
    for path in sorted((SOUNDS / "piano/sustain/steinway").glob("*.ogg")):
        match = PIANO_NAME.fullmatch(path.stem)
        if not match:
            raise ValueError(f"Unexpected piano recording: {path}")
        mode, root, layer = match.groups()
        groups.setdefault((mode, int(layer)), []).append((note_number(root), path))
    for mode in ("nosus", "sus", "nosusrel"):
        for layer, low, high in VELOCITIES:
            rows = groups[(mode, layer)]
            expected_roots = range(36, 87 if mode == "nosusrel" else 97, 2)
            if sorted(number for number, _ in rows) != list(expected_roots):
                raise ValueError(f"Incomplete piano recordings: {mode}, layer {layer}")
            section_rows = []
            for number, path in sorted(rows):
                notes = note_name(number)
                if number < 96:
                    notes += " " + note_name(number + 1)
                section_rows.append(f'\t\t"{notes}" = list({resource(path)}, {duration(path)}, 0),')
            options = f"velocity_min = {low}, velocity_max = {high}"
            if mode == "sus":
                options += ", resonant = TRUE"
            elif mode == "nosusrel":
                options += ", release_sample = TRUE, release = 0, volume_scale = 0.02"
            else:
                options += ", resonant = FALSE"
            yield from sample_section("piano", section_rows, options)


def render():
    lines = [
        "// Generated by tools/instruments/generate_samples.py.",
        "var/global/list/instrument_sustain_samples = build_instrument_sustain_samples()",
        "",
        "/// Columns: recording, duration in seconds, semitone offset.",
        "/// Space-separated keys cover consecutive semitones, starting at that offset.",
        "/proc/build_instrument_sustain_samples()",
        "\t. = list()",
    ]
    for layer, low, high in (("soft", 1, 65), ("medium", 66, 99), ("", 100, 127)):
        rows = family_rows("guitar", *IMPORTED["guitar"], layer=layer)
        lines.extend(sample_section("guitar", rows, f"velocity_min = {low}, velocity_max = {high}"))
    lines.extend(sample_section("saxophone", family_rows("saxophone", *IMPORTED["saxophone"])))
    lines.extend(piano_sections())
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the generated file is current")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            parser.exit(1, "Sample table is outdated. Run tools/instruments/generate_samples.py\n")
        print("Sample table is current.")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(text.encode()):,} bytes)")


if __name__ == "__main__":
    main()
